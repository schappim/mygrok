// installScript is shipped at GET /install. It detects OS/arch, downloads
// the matching binary from /dl, and installs it to /usr/local/bin/mygrok
// (or $MYGROK_INSTALL_DIR if set).
const installScript = `#!/usr/bin/env bash
set -euo pipefail
OS=$(uname -s | tr '[:upper:]' '[:lower:]')
ARCH=$(uname -m)
case "$ARCH" in
  x86_64|amd64) ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  armv7l|armhf) echo "armhf not supported yet"; exit 1 ;;
  *) echo "unsupported arch: $ARCH" >&2; exit 1 ;;
esac
case "$OS" in
  darwin|linux) ;;
  *) echo "unsupported OS: $OS" >&2; exit 1 ;;
esac
DEST="${MYGROK_INSTALL_DIR:-/usr/local/bin}"
URL="https://%[1]s/dl/mygrok-${OS}-${ARCH}"
TMP=$(mktemp)
echo ">> downloading mygrok ${OS}/${ARCH} from $URL"
curl -fsSL "$URL" -o "$TMP"
# Use install(1) so the destination gets a fresh inode. macOS will
# SIGKILL an ad-hoc-signed Go binary that lands at an inode the kernel
# previously cached as "won't run", which is what happens if you cp/mv
# over an existing copy.
if [ -w "$DEST" ]; then
  install -m 0755 "$TMP" "$DEST/mygrok"
else
  echo ">> sudo install to $DEST/mygrok"
  sudo install -m 0755 "$TMP" "$DEST/mygrok"
fi
rm -f "$TMP"

# Point the client at this server.
#
# Binaries built by build.sh have the address linked in, but release builds
# are deliberately generic — they must not ship pointing at anyone's server.
# Since this script is generated by the server the user is installing from,
# it knows the right answer, so it writes a config rather than leaving the
# very next command to fail with "no tunnel server configured".
#
# Only ever creates the file; an existing config is left alone.
HOME_DIR="$HOME"
if [ -n "${SUDO_USER:-}" ] && [ "$(id -u)" = "0" ]; then
  HOME_DIR="$(eval echo "~$SUDO_USER")"
fi
CONFIG="$HOME_DIR/.mygrok/config.toml"
if [ ! -e "$CONFIG" ]; then
  mkdir -p "$(dirname "$CONFIG")"
  printf 'server = "%[2]s"\n' > "$CONFIG"
  chmod 600 "$CONFIG"
  if [ -n "${SUDO_USER:-}" ] && [ "$(id -u)" = "0" ]; then
    chown -R "$SUDO_USER" "$(dirname "$CONFIG")"
  fi
  echo ">> wrote $CONFIG (server = %[2]s)"
fi

echo
echo "  installed: $DEST/mygrok"
echo
echo "  next:"
echo "    export MYGROK_AUTHTOKEN=<your-token>"
echo "    mygrok http 3000 --subdomain=foo"
echo
`

