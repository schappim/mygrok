// clientServerAddr is the host:port a client should dial to reach this
// server's control plane. --tunnel is a listen address (":7000", or
// "0.0.0.0:7000"), which is not something a client can connect to — the
// host part has to be the management hostname.
func clientServerAddr() string {
	port := "7000"
	if _, p, err := net.SplitHostPort(*tunnelAddr); err == nil && p != "" {
		port = p
	}
	return net.JoinHostPort("tunnel."+*publicHost, port)
}
