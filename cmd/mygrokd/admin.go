// isManagementHost reports whether host (no port) targets the server's own
// management endpoints (install script, downloads, landing) rather than a
// user tunnel.
func isManagementHost(hostNoPort, publicHost string) bool {
	mgmt := "tunnel." + publicHost
	return hostNoPort == mgmt
}

// serveAdmin handles requests to tunnel.<publicHost>.
//
//	GET  /install                   → bash installer
//	GET  /dl/mygrok-<os>-<arch>     → embedded client binary
//	GET  /admin/ips                 → overview: global rules + tunnel list
//	GET  /admin/ips?key=<token>     → magic-link login (issues cookie, redirects)
//	POST /admin/ips                 → add/remove a global entry
//	GET  /admin/ips/<subdomain>     → per-tunnel allow/block rules
//	POST /admin/ips/<subdomain>     → add/remove a per-tunnel entry
//	GET  /admin/passkeys            → passkey management UI
//	POST /admin/passkeys/begin      → start registration (JSON challenge)
//	POST /admin/passkeys/finish     → finish registration
//	POST /admin/passkeys/delete     → revoke one credential
//	POST /admin/locks               → toggle a tunnel's require-passkey flag
//	GET  /auth                      → passkey login UI
//	POST /auth/begin                → start assertion (JSON challenge)
//	POST /auth/finish               → finish assertion (sets session cookie)
//	GET  /auth/logout               → clear session cookie
//	anything else                   → landing page
//
// rawHeaders is the captured request bytes; br has the rest of the
// connection (used to read POST bodies on the admin pages).
func serveAdmin(conn net.Conn, rawHeaders []byte, br *bufio.Reader, acl *ipACL, reg *registry, pks *passkeyStore, wa *webauthn.WebAuthn, locks *tunnelLocks, invites *inviteStore) {
	defer conn.Close()
	method, fullURI := parseRequestLine(rawHeaders)
	path := fullURI
	rawQuery := ""
	if i := strings.Index(fullURI, "?"); i >= 0 {
		path = fullURI[:i]
		rawQuery = fullURI[i+1:]
	}
	host := "tunnel." + *publicHost

	// Every mutation on this host goes through POST. Reject cross-site ones
	// before any handler runs, rather than remembering to check in each of
	// the dozen POST branches below.
	if method == "POST" && !sameOriginPOST(rawHeaders, *publicHost) {
		writeHTTP(conn, 403, "text/plain; charset=utf-8",
			[]byte("cross-site request rejected\n"))
		return
	}

	switch {
	case path == "/install":
		body := []byte(fmt.Sprintf(installScript, host, clientServerAddr()))
		writeHTTP(conn, 200, "text/plain; charset=utf-8", body)
	case path == "/favicon.ico" || path == "/favicon.svg":
		writeHTTP(conn, 200, "image/svg+xml", []byte(faviconSVG))
	case strings.HasPrefix(path, "/dl/"):
		name := strings.TrimPrefix(path, "/dl/")
		serveBinary(conn, name)
	case path == "/admin" || path == "/admin/":
		writeHTTPRedirect(conn, "/admin/ips")
	case path == "/admin/ips":
		serveAdminIPs(conn, method, rawQuery, rawHeaders, br, acl, reg)
	case strings.HasPrefix(path, "/admin/ips/"):
		sub := strings.TrimPrefix(path, "/admin/ips/")
		serveAdminTunnelIPs(conn, method, sub, rawHeaders, br, acl, reg, locks, pks)
	case path == "/admin/passkeys":
		serveAdminPasskeys(conn, method, rawHeaders, br, pks, wa)
	case path == "/admin/passkeys/begin":
		serveAdminPasskeyBegin(conn, rawHeaders, br, pks, wa)
	case path == "/admin/passkeys/finish":
		serveAdminPasskeyFinish(conn, rawHeaders, br, pks, wa)
	case path == "/admin/passkeys/delete":
		serveAdminPasskeyDelete(conn, rawHeaders, br, pks)
	case path == "/admin/users":
		serveAdminUsers(conn, method, rawHeaders, br, pks, locks, invites)
	case path == "/admin/users/delete":
		serveAdminUsersDelete(conn, rawHeaders, br, pks, locks)
	case path == "/admin/invites":
		serveAdminInvites(conn, method, rawHeaders, br, invites)
	case path == "/admin/invites/create":
		serveAdminInvitesCreate(conn, rawHeaders, br, invites)
	case path == "/admin/locks":
		serveAdminLocks(conn, rawHeaders, br, locks, pks)
	case path == "/admin/grants":
		serveAdminGrants(conn, rawHeaders, br, locks, pks)
	case strings.HasPrefix(path, "/invite/"):
		serveInvite(conn, path, method, rawHeaders, br, pks, wa, invites)
	case path == "/auth":
		serveAuth(conn, rawQuery, rawHeaders, pks)
	case path == "/auth/begin":
		serveAuthBegin(conn, rawQuery, rawHeaders, br, pks, wa)
	case path == "/auth/finish":
		serveAuthFinish(conn, rawHeaders, br, pks, wa)
	case path == "/auth/logout":
		serveAuthLogout(conn, rawQuery, rawHeaders, pks)
	case path == "/account":
		serveAccount(conn, method, rawQuery, rawHeaders, br, pks, wa)
	case path == "/account/register/begin":
		serveAccountRegisterBegin(conn, rawHeaders, br, pks, wa)
	case path == "/account/register/finish":
		serveAccountRegisterFinish(conn, rawHeaders, br, pks, wa)
	case path == "/account/credentials/delete":
		serveAccountCredentialDelete(conn, rawHeaders, br, pks)
	default:
		writeHTTP(conn, 200, "text/html; charset=utf-8",
			[]byte(fmt.Sprintf(landingPage, host, *publicHost)))
	}
}

// serveAdminIPs renders the overview (global rules + tunnel list) on
// GET and applies a global add/remove on POST. Honors content
// negotiation: with `Accept: application/json` it returns / accepts
// JSON; otherwise it returns HTML.
//
// Auth is either:
//   - a valid mygrok_admin session cookie (set by magic-link login), or
//   - HTTP basic auth (username ignored, password = MYGROK_AUTHTOKEN), or
//   - ?key=<MYGROK_AUTHTOKEN> on the URL — magic-link login (HTML only;
//     CLI clients use HTTP basic).
func serveAdminIPs(conn net.Conn, method, rawQuery string, rawHeaders []byte, br *bufio.Reader, acl *ipACL, reg *registry) {
	if rawQuery != "" {
		if q, err := url.ParseQuery(rawQuery); err == nil {
			if key := q.Get("key"); key != "" && *authToken != "" &&
				subtle.ConstantTimeCompare([]byte(key), []byte(*authToken)) == 1 {
				sid := adminSess.issue()
				writeHTTPLoginRedirect(conn, "/admin/ips", sid)
				return
			}
		}
	}
	if !adminAuthOK(rawHeaders) {
		writeHTTPUnauthorized(conn)
		return
	}
	asJSON := wantsJSON(rawHeaders)
	if method == "POST" {
		flash, class := applyACLMutation(acl, "global", rawHeaders, br)
		if asJSON {
			writeAdminMutateJSON(conn, flash, class)
			return
		}
		writeHTTP(conn, 200, "text/html; charset=utf-8",
			renderAdminOverview(acl, reg, flash, class))
		return
	}
	if asJSON {
		writeAdminStateJSON(conn, acl, reg)
		return
	}
	writeHTTP(conn, 200, "text/html; charset=utf-8",
		renderAdminOverview(acl, reg, "", ""))
}

// serveAdminTunnelIPs handles /admin/ips/<sub> — per-tunnel allow/block
// rules. The subdomain is taken from the URL path (so the form action
// can be a relative POST without an explicit hidden field). Same JSON
// content negotiation as serveAdminIPs.
func serveAdminTunnelIPs(conn net.Conn, method, sub string, rawHeaders []byte, br *bufio.Reader, acl *ipACL, reg *registry, locks *tunnelLocks, pks *passkeyStore) {
	if !adminAuthOK(rawHeaders) {
		writeHTTPUnauthorized(conn)
		return
	}
	if !looksLikeSubdomain(sub) {
		if wantsJSON(rawHeaders) {
			writeHTTP(conn, 400, "application/json",
				[]byte(`{"ok":false,"error":"invalid subdomain in URL"}`))
			return
		}
		writeHTTP(conn, 400, "text/plain; charset=utf-8", []byte("invalid subdomain in URL"))
		return
	}
	asJSON := wantsJSON(rawHeaders)
	if method == "POST" {
		flash, class := applyACLMutation(acl, sub, rawHeaders, br)
		if asJSON {
			writeAdminMutateJSON(conn, flash, class)
			return
		}
		writeHTTP(conn, 200, "text/html; charset=utf-8",
			renderAdminTunnelPage(sub, acl, reg, locks, pks, flash, class))
		return
	}
	if asJSON {
		writeAdminTunnelJSON(conn, sub, acl, reg, locks, pks)
		return
	}
	writeHTTP(conn, 200, "text/html; charset=utf-8",
		renderAdminTunnelPage(sub, acl, reg, locks, pks, "", ""))
}

// wantsJSON reports whether the client asked for JSON via Accept.
func wantsJSON(rawHeaders []byte) bool {
	for _, line := range strings.Split(string(rawHeaders), "\r\n") {
		if !strings.HasPrefix(strings.ToLower(line), "accept:") {
			continue
		}
		v := strings.ToLower(line[len("accept:"):])
		return strings.Contains(v, "application/json")
	}
	return false
}

// writeAdminStateJSON renders the global+tunnels admin state as JSON.
// Schema is documented in `mygrok admin help`. public_host is included
// so the CLI can build clickable URLs without re-deriving them from
// --server.
func writeAdminStateJSON(conn net.Conn, acl *ipACL, reg *registry) {
	type stateOut struct {
		PublicHost        string              `json:"public_host"`
		Global            ipBucket            `json:"global"`
		TunnelsConfigured map[string]ipBucket `json:"tunnels_configured"`
		TunnelsLive       []string            `json:"tunnels_live"`
	}
	out := stateOut{
		PublicHost:        *publicHost,
		Global:            acl.SnapshotGlobal(),
		TunnelsConfigured: map[string]ipBucket{},
		TunnelsLive:       reg.activeSubdomains(),
	}
	for _, sub := range acl.TunnelsConfigured() {
		out.TunnelsConfigured[sub] = acl.SnapshotTunnel(sub)
	}
	b, _ := jsonMarshal(out)
	writeHTTP(conn, 200, "application/json", b)
}

// writeAdminTunnelJSON renders a single tunnel's bucket plus live and
// access-list state.
func writeAdminTunnelJSON(conn net.Conn, sub string, acl *ipACL, reg *registry, locks *tunnelLocks, pks *passkeyStore) {
	type allowedUser struct {
		ID   string `json:"id"`
		Name string `json:"name"`
	}
	type tunnelOut struct {
		Scope          string        `json:"scope"`
		Live           bool          `json:"live"`
		RequirePasskey bool          `json:"require_passkey"`
		AllowedUsers   []allowedUser `json:"allowed_users"`
		Allowed        []ipEntry     `json:"allowed"`
		Blocked        []ipEntry     `json:"blocked"`
	}
	bk := acl.SnapshotTunnel(sub)
	out := tunnelOut{
		Scope:          sub,
		Live:           reg.get(sub) != nil,
		RequirePasskey: locks.IsLocked(sub),
		AllowedUsers:   []allowedUser{},
		Allowed:        bk.Allowed,
		Blocked:        bk.Blocked,
	}
	for _, uid := range locks.AllowedUsers(sub) {
		name := ""
		if u := pks.FindUser(uid); u != nil {
			name = u.Name
		}
		out.AllowedUsers = append(out.AllowedUsers, allowedUser{ID: uid, Name: name})
	}
	if out.Allowed == nil {
		out.Allowed = []ipEntry{}
	}
	if out.Blocked == nil {
		out.Blocked = []ipEntry{}
	}
	b, _ := jsonMarshal(out)
	writeHTTP(conn, 200, "application/json", b)
}

// writeAdminMutateJSON renders the standard {ok, message|error} body
// returned from POSTs that ask for JSON.
func writeAdminMutateJSON(conn net.Conn, flash, class string) {
	type out struct {
		OK      bool   `json:"ok"`
		Message string `json:"message,omitempty"`
		Error   string `json:"error,omitempty"`
	}
	if class == "err" {
		b, _ := jsonMarshal(out{OK: false, Error: flash})
		writeHTTP(conn, 400, "application/json", b)
		return
	}
	b, _ := jsonMarshal(out{OK: true, Message: flash})
	writeHTTP(conn, 200, "application/json", b)
}

// jsonMarshal — small wrapper around encoding/json.
func jsonMarshal(v any) ([]byte, error) { return json.MarshalIndent(v, "", "  ") }

// applyACLMutation reads a POST form and applies the requested
// add/remove on the given scope. Returns a flash message + class.
func applyACLMutation(acl *ipACL, scope string, rawHeaders []byte, br *bufio.Reader) (string, string) {
	form, err := readPostForm(rawHeaders, br)
	if err != nil {
		return "could not parse form: " + err.Error(), "err"
	}
	list := form.Get("list")
	op := form.Get("op")
	val := strings.TrimSpace(form.Get("value"))
	note := form.Get("note")
	switch op {
	case "add":
		if err := acl.Add(scope, list, val, note); err != nil {
			return err.Error(), "err"
		}
		return "added " + val + " to " + scope + "/" + list, "ok"
	case "remove":
		if err := acl.Remove(scope, list, val); err != nil {
			return err.Error(), "err"
		}
		return "removed " + val + " from " + scope + "/" + list, "ok"
	default:
		return "unknown op: " + op, "err"
	}
}

// adminAuthOK accepts either:
//   - a valid mygrok_admin session cookie (issued by the magic-link
//     login flow on GET /admin/ips?key=...), or
//   - an Authorization: Basic ... header where the password matches
//     *authToken. Username is ignored — there's only one admin account.
func adminAuthOK(rawHeaders []byte) bool {
	if *authToken == "" {
		return false
	}
	if sid := readAdminCookie(rawHeaders); sid != "" && adminSess.valid(sid) {
		return true
	}
	var got string
	for _, line := range strings.Split(string(rawHeaders), "\r\n") {
		if strings.HasPrefix(strings.ToLower(line), "authorization:") {
			got = strings.TrimSpace(line[len("authorization:"):])
			break
		}
	}
	if !strings.HasPrefix(got, "Basic ") {
		return false
	}
	dec, err := base64.StdEncoding.DecodeString(strings.TrimSpace(got[len("Basic "):]))
	if err != nil {
		return false
	}
	parts := strings.SplitN(string(dec), ":", 2)
	if len(parts) != 2 {
		return false
	}
	return subtle.ConstantTimeCompare([]byte(parts[1]), []byte(*authToken)) == 1
}

// readAdminCookie pulls the mygrok_admin cookie value out of the raw
// request headers. Returns "" if missing. Doesn't validate — the caller
// runs that against adminSess.
func readAdminCookie(rawHeaders []byte) string {
	for _, line := range strings.Split(string(rawHeaders), "\r\n") {
		if !strings.HasPrefix(strings.ToLower(line), "cookie:") {
			continue
		}
		v := strings.TrimSpace(line[len("cookie:"):])
		for _, c := range strings.Split(v, ";") {
			c = strings.TrimSpace(c)
			eq := strings.IndexByte(c, '=')
			if eq < 0 {
				continue
			}
			if c[:eq] == adminCookieName {
				return c[eq+1:]
			}
		}
	}
	return ""
}

// writeHTTPLoginRedirect writes a 302 with both Location and Set-Cookie
// for the admin session. SameSite=Lax + HttpOnly + Secure is the right
// combination for our use — the cookie is only sent on same-site or
// top-level GET navigations, so cross-origin POSTs to /admin/ips can't
// piggyback on it (CSRF defence for the form).
func writeHTTPLoginRedirect(w io.Writer, location, sid string) {
	body := []byte("see " + location)
	hdr := fmt.Sprintf(
		"HTTP/1.1 302 Found\r\nLocation: %s\r\nSet-Cookie: %s=%s; Path=/; Max-Age=%d; HttpOnly; Secure; SameSite=Lax\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Length: %d\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n",
		location, adminCookieName, sid, int(adminSessionTTL.Seconds()), len(body))
	_, _ = w.Write([]byte(hdr))
	_, _ = w.Write(body)
}

func writeHTTPUnauthorized(w io.Writer) {
	body := []byte("Unauthorized\n")
	hdr := fmt.Sprintf("HTTP/1.1 401 Unauthorized\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Length: %d\r\nWWW-Authenticate: Basic realm=\"mygrokd admin\"\r\nConnection: close\r\nCache-Control: no-store\r\n\r\n",
		len(body))
	_, _ = w.Write([]byte(hdr))
	_, _ = w.Write(body)
}

func writeHTTPRedirect(w io.Writer, location string) {
	body := []byte("see " + location)
	hdr := fmt.Sprintf("HTTP/1.1 302 Found\r\nLocation: %s\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Length: %d\r\nConnection: close\r\n\r\n",
		location, len(body))
	_, _ = w.Write([]byte(hdr))
	_, _ = w.Write(body)
}

// writeHTTPRedirectStatus is like writeHTTPRedirect but lets the caller
// pick the status code. Use 307 (or 308) for redirects that must
// preserve the original method + body (POST/PUT/etc.); 302 changes the
// follow-up to GET in many clients.
func writeHTTPRedirectStatus(w io.Writer, code int, location string) {
	body := []byte("see " + location)
	reason := "Temporary Redirect"
	if code == 308 {
		reason = "Permanent Redirect"
	}
	hdr := fmt.Sprintf("HTTP/1.1 %d %s\r\nLocation: %s\r\nContent-Type: text/plain; charset=utf-8\r\nContent-Length: %d\r\nConnection: close\r\n\r\n",
		code, reason, location, len(body))
	_, _ = w.Write([]byte(hdr))
	_, _ = w.Write(body)
}

// readPostForm reads the request body using Content-Length from
// rawHeaders, then parses it as application/x-www-form-urlencoded. We
// cap the read at 1 MiB so a malformed admin POST can't OOM us.
func readPostForm(rawHeaders []byte, br *bufio.Reader) (url.Values, error) {
	cl := -1
	for _, line := range strings.Split(string(rawHeaders), "\r\n") {
		if strings.HasPrefix(strings.ToLower(line), "content-length:") {
			n, err := strconv.Atoi(strings.TrimSpace(line[len("content-length:"):]))
			if err == nil {
				cl = n
			}
			break
		}
	}
	if cl < 0 {
		return nil, fmt.Errorf("missing Content-Length")
	}
	if cl > 1<<20 {
		return nil, fmt.Errorf("body too large")
	}
	body := make([]byte, cl)
	if _, err := io.ReadFull(br, body); err != nil {
		return nil, err
	}
	return url.ParseQuery(string(body))
}

