// passkeyJSShim is a tiny base64url helper shared by the registration
// and login pages. WebAuthn JS APIs traffic in ArrayBuffers; the wire
// format is base64url. Inline so we don't ship a separate JS file.
const passkeyJSShim = `<script>
function b64uDecode(s) {
  s = s.replace(/-/g,'+').replace(/_/g,'/');
  while (s.length % 4) s += '=';
  return Uint8Array.from(atob(s), function(c){ return c.charCodeAt(0); });
}
function b64uEncode(buf) {
  return btoa(String.fromCharCode.apply(null, new Uint8Array(buf)))
    .replace(/\+/g,'-').replace(/\//g,'_').replace(/=+$/,'');
}
</script>`

func shortID(id string) string {
	if len(id) <= 16 {
		return id
	}
	return id[:8] + "…" + id[len(id)-8:]
}

func serveBinary(conn net.Conn, name string) {
	if !validBinaryName(name) {
		writeHTTP(conn, 404, "text/plain; charset=utf-8", []byte("not found"))
		return
	}
	f, err := clientFS.Open("embed/clients/" + name)
	if err != nil {
		writeHTTP(conn, 404, "text/plain; charset=utf-8",
			[]byte("binary not available: "+name+"\nrebuild mygrokd with the embedded clients."))
		return
	}
	defer f.Close()
	st, err := f.(fs.File).Stat()
	if err != nil {
		writeHTTP(conn, 500, "text/plain; charset=utf-8", []byte("stat error"))
		return
	}
	header := fmt.Sprintf("HTTP/1.1 200 OK\r\nContent-Type: application/octet-stream\r\nContent-Length: %d\r\nContent-Disposition: attachment; filename=\"mygrok\"\r\nConnection: close\r\n\r\n",
		st.Size())
	if _, err := conn.Write([]byte(header)); err != nil {
		return
	}
	_, _ = io.Copy(conn, f)
}

// validBinaryName allows mygrok-<os>-<arch> only.
func validBinaryName(name string) bool {
	if !strings.HasPrefix(name, "mygrok-") {
		return false
	}
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z':
		case r >= '0' && r <= '9':
		case r == '-':
		default:
			return false
		}
	}
	return true
}

func parseRequestLine(raw []byte) (method, path string) {
	br := bufio.NewReader(bytes.NewReader(raw))
	line, err := br.ReadString('\n')
	if err != nil && line == "" {
		return "", ""
	}
	parts := strings.SplitN(strings.TrimRight(line, "\r\n"), " ", 3)
	if len(parts) < 2 {
		return "", ""
	}
	return parts[0], parts[1]
}

// writeHTTP writes a complete HTTP/1.1 response (closes the connection).
func writeHTTP(w io.Writer, code int, contentType string, body []byte) {
	status := statusText(code)
	// HSTS whenever a TLS listener exists. Browsers ignore the header on a
	// plaintext response, so sending it unconditionally is harmless and
	// saves threading "was this TLS?" through every caller.
	hsts := ""
	if *httpsAddr != "" {
		hsts = "Strict-Transport-Security: max-age=31536000\r\n"
	}
	hdr := fmt.Sprintf("HTTP/1.1 %d %s\r\nContent-Type: %s\r\nContent-Length: %d\r\nConnection: close\r\nCache-Control: no-store\r\n%s\r\n",
		code, status, contentType, len(body), hsts)
	_, _ = w.Write([]byte(hdr))
	_, _ = w.Write(body)
}

// sameOriginPOST guards admin mutations against cross-site requests.
//
// The admin session cookie is SameSite=Lax, which already blocks
// cross-site POSTs — but HTTP Basic auth is also accepted, and browsers
// replay cached Basic credentials on any request to the realm regardless of
// SameSite. So a page on another site could POST to /admin/ips and have it
// authenticate. Checking Origin (falling back to Referer) closes that
// without needing a token in every form.
//
// A missing Origin *and* Referer is allowed: that's what non-browser
// clients like `mygrok admin` and curl send, and they aren't the threat
// here — a cross-site attacker cannot suppress both from a browser.
func sameOriginPOST(rawHeaders []byte, publicHost string) bool {
	origin, referer := "", ""
	for _, line := range strings.Split(string(rawHeaders), "\r\n") {
		lower := strings.ToLower(line)
		switch {
		case strings.HasPrefix(lower, "origin:"):
			origin = strings.TrimSpace(line[len("origin:"):])
		case strings.HasPrefix(lower, "referer:"):
			referer = strings.TrimSpace(line[len("referer:"):])
		}
	}
	check := origin
	if check == "" {
		check = referer
	}
	if check == "" {
		return true
	}
	u, err := url.Parse(check)
	if err != nil {
		return false
	}
	return strings.ToLower(u.Hostname()) == "tunnel."+strings.ToLower(publicHost)
}

func statusText(code int) string {
	switch code {
	case 200:
		return "OK"
	case 400:
		return "Bad Request"
	case 404:
		return "Not Found"
	case 500:
		return "Internal Server Error"
	case 502:
		return "Bad Gateway"
	default:
		return "OK"
	}
}

