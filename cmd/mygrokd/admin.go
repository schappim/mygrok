// adminSessions is an in-memory store of active admin session cookies.
// It survives process lifetime only — restart and you re-login. Each
// entry is a random 32-byte hex token mapped to its expiry.
type adminSessions struct {
	mu sync.Mutex
	m  map[string]time.Time
}

var adminSess = &adminSessions{m: map[string]time.Time{}}

const adminCookieName = "mygrok_admin"
const adminSessionTTL = 24 * time.Hour

func (s *adminSessions) issue() string {
	var b [32]byte
	if _, err := rand.Read(b[:]); err != nil {
		// Fall back to time-based — extremely unlikely path.
		return fmt.Sprintf("t-%d", time.Now().UnixNano())
	}
	id := hex.EncodeToString(b[:])
	s.mu.Lock()
	s.m[id] = time.Now().Add(adminSessionTTL)
	s.mu.Unlock()
	return id
}

func (s *adminSessions) valid(id string) bool {
	if id == "" {
		return false
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	exp, ok := s.m[id]
	if !ok {
		return false
	}
	if time.Now().After(exp) {
		delete(s.m, id)
		return false
	}
	return true
}

